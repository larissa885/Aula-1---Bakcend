CREATE TABLE IF NOT EXISTS produtos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL,
  valor NUMERIC(12, 2) NOT NULL CHECK (valor >= 0),
  quantidade INTEGER NOT NULL DEFAULT 0 CHECK (quantidade >= 0),
  categoria TEXT NOT NULL,
  unidade_medida TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS movimentacoes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  produtos_id BIGINT NOT NULL REFERENCES produtos(id),
  tipo TEXT NOT NULL CHECK (tipo IN ('entrada', 'saida')),
  quantidade INTEGER NOT NULL CHECK (quantidade > 0),
  datas DATE NOT NULL DEFAULT CURRENT_DATE
);

CREATE INDEX IF NOT EXISTS movimentacoes_data_tipo_idx ON movimentacoes (datas, tipo);
CREATE INDEX IF NOT EXISTS movimentacoes_produto_idx ON movimentacoes (produtos_id);
